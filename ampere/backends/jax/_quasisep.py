r"""The quasiseparable recursions behind :class:`~ampere.backends.jax.QuasisepGP`.

Two providers of one five-function surface (W7.10)
--------------------------------------------------
:class:`~ampere.backends.jax.QuasisepGP` needs four operations on a rank-``J``
semiseparable matrix, and nothing else — every density, conditional,
whitening transform and leave-one-out term it computes is a composition of
them. This module supplies them twice, behind one interface, so the solver is
written once and the *recursion* is what varies:

* :data:`CELERITE2` — thin calls into ``celerite2.jax.ops``, celerite2's
  compiled C++ kernels registered as XLA custom calls. Linear in N at about
  0.25 µs per point on the CPU, with hand-written reverse passes; but its
  primitives have **CPU lowerings alone** (W6.18's finding) and **no ``vmap``
  batching rule**, so it can neither run on an accelerator nor be batched;
* :data:`SCAN` — the same recursions written in jax itself, as
  :func:`jax.lax.scan` over the samples with a ``J x J`` (or ``J x nrhs``)
  carry. Pure ``jnp``, so it lowers wherever XLA does, ``vmap`` batches it, and
  jax's own reverse mode differentiates it. This is the provider the solver
  uses on an accelerator, where celerite2 cannot run at all.

The torch backend's :mod:`ampere.backends.torch._celerite` names the same
surface and explains why *torch* could not have the second provider: a
recursion written in torch is a Python loop of N autograd nodes, measured
there at ~1 800x slower. jax has ``lax.scan``, which stages the loop body once;
that is the whole reason the second provider exists.

The convention, stated once
---------------------------
celerite2's, unchanged: ``K + diag(a) = L D Lᵀ`` with ``L`` **unit** lower
triangular and semiseparable of rank ``J``,

.. math::
    L_{nm} = \sum_j U_{nj} W_{mj} e^{-c_j (t_n - t_m)}\quad (n > m),
    \qquad L_{nn} = 1,

where ``t`` (sorted, ``(N,)``), ``c`` (``(J,)``), ``a`` (``(N,)``, the full
diagonal, kernel variance included) and the generators ``U``, ``V``
(``(N, J)``) describe ``K + diag(a)`` itself:
``K_{nm} = Σ_j U_{nj} V_{mj} e^{-c_j (t_n - t_m)}`` for ``n > m``.

* :meth:`factor` ``(t, c, a, U, V) → (d, W)``: the diagonal of ``D`` and the
  second generator of ``L``;
* :meth:`solve_lower` ``(t, c, U, W, Y)``: ``L⁻¹ Y``;
* :meth:`solve_upper` ``(t, c, U, W, Y)``: ``L⁻ᵀ Y``;
* :meth:`matmul_lower` ``(t, c, U, V, Y)``: the strictly lower part of the
  semiseparable matrix generated by ``(U, V)`` applied to ``Y`` — with ``W``
  for ``V`` that is ``(L - I) Y``, which is what ``dot_tril`` needs.

Each is O(N J²) per right-hand side.

The recursions the scan provider writes
---------------------------------------
With ``p_n = e^{-c (t_n - t_{n-1})}`` (elementwise over the ``J`` rates), the
pre-conditioned recursions of Foreman-Mackey et al. (2017, AJ 154, 220) in the
form celerite2 implements them (and whose reverse passes Foreman-Mackey 2018,
RNAAS 2, 31 derives) are:

**factorisation**, from ``S_0 = 0``, ``d_0 = a_0``, ``W_0 = V_0 / d_0``:

.. math::
    S_n = \mathrm{diag}(p_n)\,(S_{n-1} + d_{n-1} W_{n-1} W_{n-1}^\top)\,
          \mathrm{diag}(p_n),\quad
    d_n = a_n - U_n^\top S_n U_n,\quad
    W_n = (V_n - S_n U_n) / d_n;

**forward substitution** (``L z = y``), from ``F_0 = 0``, ``z_0 = y_0``:

.. math::
    F_n = \mathrm{diag}(p_n)\,(F_{n-1} + W_{n-1} z_{n-1}^\top),\quad
    z_n = y_n - U_n^\top F_n;

**backward substitution** (``Lᵀ z = y``), from ``F_{N-1} = 0``,
``z_{N-1} = y_{N-1}``:

.. math::
    F_n = \mathrm{diag}(p_{n+1})\,(F_{n+1} + U_{n+1} z_{n+1}^\top),\quad
    z_n = y_n - W_n^\top F_n;

**strictly lower product**, from ``F_0 = 0``, ``z_0 = 0``:

.. math::
    F_n = \mathrm{diag}(p_n)\,(F_{n-1} + V_{n-1} y_{n-1}^\top),\quad
    z_n = U_n^\top F_n.

Each is checked against celerite2 element by element in
``tests/backends/test_jax.py`` (random ``(t, c, a, U, V)`` at rank 3, to 1e-10
relative) as well as through the solver against the dense Cholesky.

Gradients and failure
---------------------
The scan provider has **no custom VJP**: a ``scan`` is differentiable, and
jax's reverse mode saves one carry per step, O(N J²) memory — measured in
``docs/design/performance_memo.md`` §9. A failed factorisation (a pivot
``d_n`` that is not positive and finite) makes the **whole** of ``d`` NaN,
the torch shim's convention: every caller then sees a non-finite number
wherever ``d`` enters — the log-determinant, a division, a square root —
which the solver turns into a refusal on the contract path and into ``-inf``
on the traced one. celerite2 signals the same failure by zeroing ``d`` from
the failed pivot onwards, which reaches the same refusals through ``log 0``
and ``1/0``; the scan's NaN is the stricter of the two, since it also poisons
``sqrt(d)`` in the whitening transform, where a zero would pass silently.
"""

from __future__ import annotations

import functools
from typing import Any, ClassVar

import jax
import jax.numpy as jnp

from ampere.core.exceptions import LikelihoodError

from ._config import x64_enabled

__all__ = [
    "CELERITE2",
    "PROVIDERS",
    "SCAN",
    "QuasisepProvider",
]


@functools.cache
def _celerite2_jax() -> Any:
    """``celerite2.jax``, imported **only after** x64 is already on.

    The deferral is the whole point (see :mod:`ampere.backends.jax.gp`'s
    module docstring). ``celerite2.jax``'s ``__init__`` reads
    ``jax_enable_x64`` and, if it is off, warns and calls ``config.update``
    itself — which is exactly what ``lowering.md`` §10.2(a) forbids ampere from
    doing, done to ampere by a dependency. Two consequences would follow from
    importing it at module level: a user who imported ``ampere.backends.jax``
    would have the process-global flag flipped by an ``import`` statement they
    did not write, and :func:`~ampere.backends.jax._config.require_x64` — the
    guard that is supposed to *refuse* when the flag is off — would be
    satisfied by a flag celerite2 had just set on their behalf.

    So the import happens here, on first use, and every caller has already
    passed ``require_x64`` at construction. The check below states that
    invariant rather than trusting it: if it ever fires, the deferral has been
    routed around and the guard has stopped meaning anything. The scan
    provider never calls this, so a solver on it never imports celerite2.

    :func:`functools.cache` makes it a singleton, so the module object is
    stable for celerite2's own caches.
    """
    if not x64_enabled():
        raise LikelihoodError(
            "ampere tried to import celerite2.jax while jax's x64 mode was off. It must never "
            "do that: celerite2.jax turns x64 on as an import side effect, which would make "
            "ampere.backends.jax.require_x64() pass on a flag nobody in your program set "
            "(lowering.md §10.2(a)). Call ampere.backends.jax.configure_x64() first. Reaching "
            "this message means the deferral in ampere.backends.jax.gp has been routed around, "
            "which is a bug in ampere rather than in your program."
        )
    import celerite2.jax

    return celerite2.jax


class QuasisepProvider:
    """One implementation of the five-function surface this module documents.

    Stateless: an instance is a namespace with capability flags, shared by
    every solver that chose it. Subclasses override the four operations.
    """

    #: The ``provider=`` spelling that selects this one.
    NAME: ClassVar[str] = ""
    #: What ``QuasisepGP.provenance_config()`` records as the ``library``.
    LIBRARY: ClassVar[str] = ""
    #: Whether ``jax.vmap`` can batch a density built on it.
    BATCHABLE: ClassVar[bool] = False
    #: The jax platforms it has lowerings for; ``None`` means every platform.
    PLATFORMS: ClassVar[frozenset[str] | None] = None

    def factor(self, t: Any, c: Any, a: Any, U: Any, V: Any) -> tuple[jax.Array, jax.Array]:
        """``K + diag(a) = L D Lᵀ``: ``(d, W)``."""
        raise NotImplementedError

    def solve_lower(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        """``L⁻¹ Y`` for an ``(N, nrhs)`` *Y*."""
        raise NotImplementedError

    def solve_upper(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        """``L⁻ᵀ Y`` for an ``(N, nrhs)`` *Y*."""
        raise NotImplementedError

    def matmul_lower(self, t: Any, c: Any, U: Any, V: Any, Y: Any) -> jax.Array:
        """``tril(U Vᵀ ⊙ decay, -1) Y`` for an ``(N, nrhs)`` *Y*."""
        raise NotImplementedError

    def __repr__(self) -> str:
        return f"<quasiseparable provider {self.NAME!r}>"


class _Celerite2Provider(QuasisepProvider):
    """celerite2's compiled kernels, through ``celerite2.jax.ops`` (CPU only)."""

    NAME = "celerite2"
    LIBRARY = "celerite2.jax"
    BATCHABLE = False
    PLATFORMS = frozenset({"cpu"})

    def factor(self, t: Any, c: Any, a: Any, U: Any, V: Any) -> tuple[jax.Array, jax.Array]:
        return _celerite2_jax().ops.factor(t, c, a, U, V)

    def solve_lower(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        return _celerite2_jax().ops.solve_lower(t, c, U, W, Y)

    def solve_upper(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        return _celerite2_jax().ops.solve_upper(t, c, U, W, Y)

    def matmul_lower(self, t: Any, c: Any, U: Any, V: Any, Y: Any) -> jax.Array:
        return _celerite2_jax().ops.matmul_lower(t, c, U, V, Y)


#: How many recursion steps each iteration of the compiled loop runs. **Not a
#: tuning knob but a correctness-of-scaling one** (``performance_memo.md`` §9):
#: with ``unroll=1`` XLA's CPU backend makes every iteration of a ``scan`` that
#: stacks per-step outputs cost time proportional to N — the "quadratic in
#: practice" W2.5 slice 2 measured on tinygp — while any unroll of two or more
#: keeps the loop linear. Two was the fastest of 2, 8, 16, 32 and 64.
_UNROLL = 2


def _decays(t: Any, c: Any) -> jax.Array:
    """``p_n = e^{-c (t_n - t_{n-1})}`` for ``n = 1 … N-1``, shape ``(N-1, J)``.

    Written as celerite2 writes it, ``exp(c (t_{n-1} - t_n))``, so the two
    providers exponentiate the same number.
    """
    return jnp.exp(c[None, :] * (t[:-1] - t[1:])[:, None])


class _ScanProvider(QuasisepProvider):
    """The recursions as :func:`jax.lax.scan`, in pure ``jnp`` (any platform)."""

    NAME = "scan"
    LIBRARY = "ampere.jax.scan"
    BATCHABLE = True
    PLATFORMS = None

    def factor(self, t: Any, c: Any, a: Any, U: Any, V: Any) -> tuple[jax.Array, jax.Array]:
        rank = U.shape[1]
        first_d = a[0]
        first_w = V[0] / first_d

        def step(carry: Any, row: Any) -> tuple[Any, Any]:
            state, d_prev, w_prev = carry
            p, a_n, u_n, v_n = row
            state = p[:, None] * (state + d_prev * jnp.outer(w_prev, w_prev)) * p[None, :]
            projected = state @ u_n
            d_n = a_n - projected @ u_n
            w_n = (v_n - projected) / d_n
            return (state, d_n, w_n), (d_n, w_n)

        initial = (jnp.zeros((rank, rank), dtype=U.dtype), first_d, first_w)
        _, (d_rest, w_rest) = jax.lax.scan(
            step, initial, (_decays(t, c), a[1:], U[1:], V[1:]), unroll=_UNROLL
        )
        d = jnp.concatenate([first_d[None], d_rest])
        W = jnp.concatenate([first_w[None, :], w_rest], axis=0)
        # A failed pivot poisons the whole of d (the module docstring's
        # "Gradients and failure"): every caller then sees it wherever d enters.
        usable = jnp.all(d > 0.0) & jnp.all(jnp.isfinite(d))
        return jnp.where(usable, d, jnp.nan), W

    def solve_lower(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        def step(carry: Any, row: Any) -> tuple[Any, Any]:
            state, z_prev = carry
            p, u_n, w_prev, y_n = row
            state = p[:, None] * (state + jnp.outer(w_prev, z_prev))
            z_n = y_n - u_n @ state
            return (state, z_n), z_n

        initial = (jnp.zeros((U.shape[1], Y.shape[1]), dtype=Y.dtype), Y[0])
        _, rest = jax.lax.scan(step, initial, (_decays(t, c), U[1:], W[:-1], Y[1:]), unroll=_UNROLL)
        return jnp.concatenate([Y[:1], rest], axis=0)

    def solve_upper(self, t: Any, c: Any, U: Any, W: Any, Y: Any) -> jax.Array:
        def step(carry: Any, row: Any) -> tuple[Any, Any]:
            state, z_next = carry
            p, u_next, w_n, y_n = row
            state = p[:, None] * (state + jnp.outer(u_next, z_next))
            z_n = y_n - w_n @ state
            return (state, z_n), z_n

        initial = (jnp.zeros((U.shape[1], Y.shape[1]), dtype=Y.dtype), Y[-1])
        _, rest = jax.lax.scan(
            step, initial, (_decays(t, c), U[1:], W[:-1], Y[:-1]), reverse=True, unroll=_UNROLL
        )
        return jnp.concatenate([rest, Y[-1:]], axis=0)

    def matmul_lower(self, t: Any, c: Any, U: Any, V: Any, Y: Any) -> jax.Array:
        def step(state: Any, row: Any) -> tuple[Any, Any]:
            p, u_n, v_prev, y_prev = row
            state = p[:, None] * (state + jnp.outer(v_prev, y_prev))
            return state, u_n @ state

        initial = jnp.zeros((U.shape[1], Y.shape[1]), dtype=Y.dtype)
        _, rest = jax.lax.scan(
            step, initial, (_decays(t, c), U[1:], V[:-1], Y[:-1]), unroll=_UNROLL
        )
        return jnp.concatenate([jnp.zeros_like(Y[:1]), rest], axis=0)


#: celerite2's compiled kernels: the CPU provider.
CELERITE2: QuasisepProvider = _Celerite2Provider()
#: The ``lax.scan`` recursions: the accelerator provider, and batchable.
SCAN: QuasisepProvider = _ScanProvider()
#: Every provider by its ``provider=`` spelling.
PROVIDERS: dict[str, QuasisepProvider] = {CELERITE2.NAME: CELERITE2, SCAN.NAME: SCAN}
