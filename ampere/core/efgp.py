r"""Equispaced Fourier features: the second reduced-rank spectral solver (**W5.6**).

``DEVELOPMENT_PLAN.md`` §5's Phase 5 rule is that an approximate solver is
**chosen by measurement**, and W5.6 is that measurement: EFGP and Vecchia
(:mod:`ampere.core.vecchia`) implemented far enough to benchmark against W5.4's
:class:`~ampere.core.HilbertSpaceGP` and against :class:`~ampere.core.DenseGP`
on an image. This module is the EFGP half. It is a **reference-only
prototype**: numpy and scipy, no torch or jax twin, and it is not one of the
declared strategy slots of ``likelihoods.md`` §7 — the bake-off's decision-log
row says which of the two is promoted to a full three-backend solver.

The method
----------
Greengard, Rachh & Barnett (2023), *Equispaced Fourier representations for
efficient Gaussian process regression from a billion data points*. Bochner's
theorem writes a stationary kernel as the inverse transform of its spectral
density; ampere's convention (:meth:`~ampere.core.kernels.Kernel.spectral_density`)
is

.. math::
    k(\mathbf r) = (2\pi)^{-d} \int S(\|\boldsymbol\omega\|)\,
    e^{i \boldsymbol\omega \cdot \mathbf r}\, \mathrm d^d \boldsymbol\omega .

Discretise that integral on an **equispaced** frequency grid
:math:`\boldsymbol\omega_{\mathbf j} = (h_1 j_1, \ldots, h_d j_d)`,
:math:`j_k \in \{-M_k, \ldots, M_k\}`, by the rectangle rule:

.. math::
    k(\mathbf r) \;\approx\; \sum_{\mathbf j} w_{\mathbf j}\,
    e^{i \boldsymbol\omega_{\mathbf j} \cdot \mathbf r},
    \qquad
    w_{\mathbf j} = \frac{\prod_k h_k}{(2\pi)^d}\,
        S\big(\|\boldsymbol\omega_{\mathbf j}\|\big) \; \ge 0 ,

so that with :math:`\tilde\Phi_{p\mathbf j} = \sqrt{w_{\mathbf j}}\,
e^{i\boldsymbol\omega_{\mathbf j}\cdot \mathbf x_p}` the covariance is
:math:`K \approx \tilde\Phi \tilde\Phi^{\mathsf H}` — a rank-``m``
factorisation, exactly as HSGP's is, and every quantity follows from the same
Woodbury identity on :math:`M = I_m + \tilde\Phi^{\mathsf H} D^{-1}
\tilde\Phi`.

**Why bother, when HSGP already factorises the covariance that way.** Because
the grid is equispaced, and that is the whole method:

.. math::
    \big(\tilde\Phi^{\mathsf H} D^{-1} \tilde\Phi\big)_{\mathbf j \mathbf k}
    = \sqrt{w_{\mathbf j} w_{\mathbf k}}
      \sum_p \frac{e^{-i (\boldsymbol\omega_{\mathbf j} -
      \boldsymbol\omega_{\mathbf k})\cdot \mathbf x_p}}{D_p}
    = \sqrt{w_{\mathbf j} w_{\mathbf k}}\; G[\mathbf j - \mathbf k] ,

which depends on the index **difference** alone. The normal matrix is
therefore (block-)Toeplitz, generated by one array :math:`G` on the difference
grid, and three costs collapse at once:

* :math:`G` is a *separable* sum — :math:`e^{-i h\boldsymbol\delta \cdot
  \mathbf x} = \prod_k e^{-i h_k \delta_k x_k}` — so it is assembled by one
  complex GEMM per axis pair at :math:`O(N\,2^d m)` rather than by forming
  :math:`\tilde\Phi^{\mathsf H} D^{-1}\tilde\Phi` at :math:`O(N m^2)`. **That
  factor of** :math:`m/2^d` **is the measured win over HSGP**, and at image
  scale it is two orders of magnitude.
* the ``(N, m)`` block is never formed for the marginal likelihood, so the
  memory is :math:`O(N m^{1/d} d + m^2)` rather than :math:`O(N m)`;
* the Toeplitz matrix multiplies a vector by FFT in :math:`O(m \log m)`
  (:func:`toeplitz_matvec`), so a *solve* need not be a factorisation.

What the FFT does **not** give, and what W5.6 measures
------------------------------------------------------
Greengard et al.'s target is the posterior mean, which is a linear solve, and
for that the story ends at :math:`O(N + m\log m)`: conjugate gradients on a
matrix that is :math:`I` plus something positive semi-definite converges in a
handful of iterations, each an FFT (:func:`solve_iterative`). A **marginal
likelihood** needs :math:`\log|M|` as well, and a Toeplitz determinant has no
FFT: the honest options are an :math:`O(m^3)` Cholesky or a stochastic
Lanczos-quadrature estimate, and a stochastic log-determinant inside an MCMC
likelihood is a noisy target rather than a cheap one. This solver therefore
factorises :math:`M` with a Cholesky and says so; :func:`solve_iterative` is
supplied beside it so the bake-off can measure what the iterative route does
and does not remove. See ``docs/design/contracts/likelihoods.md`` §7's
bake-off subsection for the measured numbers.

The approximation's two parameters
----------------------------------
The same two HSGP has, meaning the same things, so the two are comparable at a
glance:

``basis_size``
    Grid points **per axis**, and odd, because the grid is symmetric about
    :math:`\boldsymbol\omega = 0`. The total ``m`` is their product. It sets
    the truncation: the grid reaches :math:`M_k h_k`, and what is cut off is
    the tail of :math:`S` beyond it.
``boundary_factor``
    The spacing, through :math:`h_k = \pi / (c\,S_k)` for a data half-extent
    :math:`S_k`. Poisson summation makes the rectangle rule's error *exactly*
    the periodisation :math:`\sum_{n \ne 0} k(\mathbf r + 2\pi \mathbf n / h)`,
    so :math:`2\pi/h_k = 2 c S_k` must exceed the data's own diameter
    :math:`2 S_k` with room for the kernel to decay — which is ``c > 1``, the
    identical statement to HSGP's box needing to contain the data with room to
    spare. Refining one of the two alone converges to the wrong answer, as
    ``likelihoods.md`` §7's measured sweep shows for HSGP.

Both are dataclass fields, so they enter ``Likelihood.to_spec``'s hash
(W5.4's correction to fold-in 10: an approximation changes the likelihood's
value, so it is a declaration and not configuration), and both are repeated in
:meth:`EquispacedFourierGP.provenance_config`.
"""

