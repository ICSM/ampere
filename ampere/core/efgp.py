def _centred(grid: FourierGrid, points: np.ndarray) -> np.ndarray:
    """*points* about the grid's centre, ``(n, d)``."""
    return np.ascontiguousarray(points - grid.centre[None, :], dtype=DTYPE)


def _phases(grid: FourierGrid, centred: np.ndarray, axis: int, orders: np.ndarray) -> np.ndarray:
    """``(n, t)`` block of :math:`e^{i h_a j x_a}` for the integers *orders*."""
    argument = float(grid.spacing[axis]) * np.outer(centred[:, axis], orders.astype(DTYPE))
    return np.exp(1j * argument)


def _contract(weights: np.ndarray, factors: Sequence[np.ndarray]) -> np.ndarray:
    """:math:`\\sum_p w_p \\prod_a F_a[p, t_a]`, shaped ``(t_0, ..., t_{d-1})``.

    The one routine that gives EFGP its cost. Written as GEMMs rather than as
    an ``einsum`` over an ``(n, t_0, t_1)`` intermediate, because the whole
    point is never to allocate an ``N``-by-``m`` block: the one- and two-axis
    cases are a matrix-vector and a matrix-matrix product, and a third axis is
    a loop of two-axis contractions, so the peak allocation stays
    ``O(N max_a t_a)`` at every dimension.
    """
    if len(factors) == 1:
        return factors[0].T @ weights.astype(CDTYPE)
    if len(factors) == 2:
        return (factors[0] * weights[:, None]).T @ factors[1]
    head = factors[0]
    return np.stack(
        [_contract(weights * head[:, index], factors[1:]) for index in range(head.shape[1])],
        axis=0,
    )


def toeplitz_generator(grid: FourierGrid, points: np.ndarray, weights: np.ndarray) -> np.ndarray:
    """:math:`G[\\boldsymbol\\delta] = \\sum_p w_p e^{-i h \\boldsymbol\\delta \\cdot x_p}`.

    Shaped ``(2 n_0 - 1, ..., 2 n_{d-1} - 1)`` with :math:`\\boldsymbol\\delta
    = 0` at the centre of each axis: the generator of the Toeplitz normal
    matrix, and the array an FFT-based matvec embeds in a circulant.

    *weights* is :math:`1/D_p` for the normal matrix; a residual over the noise
    variance gives the right-hand side instead, on the smaller grid.
    """
    centred = _centred(grid, points)
    factors = [
        _phases(grid, centred, axis, -np.arange(-(count - 1), count, dtype=np.int64))
        for axis, count in enumerate(grid.counts)
    ]
    return np.asarray(_contract(np.asarray(weights, dtype=DTYPE), factors), dtype=CDTYPE)


def _projection(grid: FourierGrid, points: np.ndarray, weights: np.ndarray) -> np.ndarray:
    """:math:`\\sum_p w_p e^{-i\\boldsymbol\\omega_{\\mathbf j}\\cdot x_p}`, ``(m,)``.

    The unweighted half of :math:`\\tilde\\Phi^{\\mathsf H} D^{-1} r`, on the
    grid itself rather than on the difference grid.
    """
    centred = _centred(grid, points)
    factors = [
        _phases(grid, centred, axis, -np.arange(-(count // 2), count // 2 + 1, dtype=np.int64))
        for axis, count in enumerate(grid.counts)
    ]
    block = _contract(np.asarray(weights, dtype=DTYPE), factors)
    return np.asarray(block, dtype=CDTYPE).reshape(-1)


def toeplitz_matrix(grid: FourierGrid, generator: np.ndarray) -> np.ndarray:
    """The dense ``(m, m)`` (block-)Toeplitz matrix *generator* generates.

    Formed explicitly because the solver factorises it: a Cholesky needs the
    matrix, and :math:`O(m^2)` storage is small beside the :math:`O(N m)` block
    the method exists to avoid. :func:`toeplitz_matvec` is the route that never
    forms it.
    """
    counts = np.asarray(grid.counts, dtype=np.int64)
    indices = grid.orders + (counts - 1) // 2  # 0-based multi-index of each member
    difference = indices[:, None, :] - indices[None, :, :] + (counts - 1)[None, None, :]
    return np.asarray(generator[tuple(difference[..., axis] for axis in range(len(grid.counts)))])


def toeplitz_matvec(grid: FourierGrid, generator: np.ndarray, vector: np.ndarray) -> np.ndarray:
    """The Toeplitz product :math:`T v`, by circulant embedding and FFT.

    :math:`O(m \\log m)` per call, with no ``(m, m)`` matrix anywhere. This is
    the operation Greengard et al.'s :math:`O(N + m \\log m)` claim rests on,
    and :func:`solve_iterative` is what it buys; the log-determinant a marginal
    likelihood also needs is what it does not (see the module docstring).
    """
    counts = grid.counts
    padded = tuple(2 * count - 1 for count in counts)
    # The circulant's first column: position ``i`` on an axis stands for the
    # index difference ``i`` while ``i < n`` and for ``i - (2n - 1)``, a
    # negative difference, after it. Every axis wraps **independently**, so the
    # map is built per axis and taken as an outer index — a 2-D embedding has
    # four corners, not two, and filling only the two that a 1-D one has is
    # the mistake this comment exists to prevent recurring.
    maps = []
    for count in counts:
        positions = np.arange(2 * count - 1)
        difference = np.where(positions < count, positions, positions - (2 * count - 1))
        maps.append(difference + (count - 1))
    embedded = np.asarray(generator[np.ix_(*maps)], dtype=CDTYPE)
    forward = tuple(slice(0, count) for count in counts)
    block = np.zeros(padded, dtype=CDTYPE)
    block[forward] = np.reshape(vector, counts)
    product = np.fft.ifftn(np.fft.fftn(embedded) * np.fft.fftn(block))
    return np.asarray(product[forward].reshape(-1), dtype=CDTYPE)


def solve_iterative(
    grid: FourierGrid,
    generator: np.ndarray,
    root_weights: np.ndarray,
    right: np.ndarray,
    *,
    tolerance: float = DEFAULT_TOLERANCE,
    max_iterations: int = DEFAULT_MAX_ITERATIONS,
) -> tuple[np.ndarray, int]:
    """:math:`M^{-1} b` by conjugate gradients on FFT matvecs, and the iteration count.

    :math:`M = I_m + \\operatorname{diag}(\\sqrt w)\\,T\\,\\operatorname{diag}
    (\\sqrt w)` is Hermitian and :math:`\\succeq I`, so CG converges on it
    unconditionally and quickly. Supplied for the W5.6 bake-off rather than
    used by :class:`EquispacedFourierGP`, which needs :math:`\\log|M|` and so
    factorises instead; the two are measured side by side so the table can say
    what the iterative route removes and what it does not.
    """
    iterations = 0

    def apply(vector: np.ndarray) -> np.ndarray:
        nonlocal iterations
        iterations += 1
        scaled = root_weights.astype(CDTYPE) * vector
        return vector + root_weights.astype(CDTYPE) * toeplitz_matvec(grid, generator, scaled)

    target = np.asarray(right, dtype=CDTYPE)
    solution = np.zeros_like(target)
    residual = target - apply(solution)
    direction = residual.copy()
    squared = float(np.real(np.vdot(residual, residual)))
    goal = tolerance * tolerance * float(np.real(np.vdot(target, target)))
    for _ in range(max_iterations):
        if squared <= goal:
            break
        applied = apply(direction)
        step = squared / float(np.real(np.vdot(direction, applied)))
        solution = solution + step * direction
        residual = residual - step * applied
        updated = float(np.real(np.vdot(residual, residual)))
        direction = residual + (updated / squared) * direction
        squared = updated
    return solution, iterations


def real_features(grid: FourierGrid, weights: np.ndarray, points: np.ndarray) -> np.ndarray:
    """A **real** ``(n, m)`` factor :math:`\\Psi` with :math:`\\Psi\\Psi^{\\mathsf T} = K`.

    The complex representation is what makes the normal matrix Toeplitz, and it
    is the wrong one for :meth:`~ampere.core.GPSolver.latent_transform`, which
    must map real whitened draws to a real GP draw. Pairing
    :math:`\\boldsymbol\\omega` with :math:`-\\boldsymbol\\omega` — which the
    symmetric grid always can, and which an even count could not — turns the
    sum into

    .. math::
        K(\\mathbf r) = w_{\\mathbf 0}
        + \\sum_{\\text{pairs}} 2 w_{\\mathbf j}\\cos(\\boldsymbol\\omega_{\\mathbf j}
          \\cdot \\mathbf r) ,

    and a cosine of a difference splits into
    :math:`\\cos\\cos + \\sin\\sin`. So each conjugate pair contributes two
    real columns and the zero frequency one: exactly ``m`` of them, which is
    why the latent block is the same size in either representation.
    """
    centred = _centred(grid, points)
    argument = centred @ grid.frequencies.T  # (n, m)
    orders = grid.orders
    leading = np.zeros(orders.shape[0], dtype=np.int64)
    nonzero = orders != 0
    first = np.argmax(nonzero, axis=1)
    has_any = np.any(nonzero, axis=1)
    leading[has_any] = orders[np.arange(orders.shape[0])[has_any], first[has_any]]
    positive = leading > 0
    zero = ~has_any
    columns = [np.sqrt(weights[zero])[None, :] * np.ones((centred.shape[0], int(np.sum(zero))))]
    root = np.sqrt(2.0 * weights[positive])[None, :]
    columns.append(root * np.cos(argument[:, positive]))
    columns.append(root * np.sin(argument[:, positive]))
    return np.ascontiguousarray(np.concatenate(columns, axis=1), dtype=DTYPE)


