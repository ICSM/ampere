@dataclasses.dataclass(frozen=True)
class FourierGrid:
    """Where the frequency grid is: spacing, extent, and the members themselves.

    Every field is a constant of the *data* and of the declaration — no fitted
    value enters — which is what keeps the representation a fixed linear one
    and the latent block a fixed size.

    Attributes
    ----------
    centre
        ``(d,)`` midpoint of the data's extent on each selected axis. Phases
        are evaluated on centred coordinates, so the aliasing period is
        measured about the middle of the data rather than about the origin.
    half_width
        ``(d,)`` :math:`L_k = c\\,S_k`, the data's half-extent scaled by the
        boundary factor.
    spacing
        ``(d,)`` :math:`h_k = \\pi / L_k`.
    counts
        Grid points per axis, odd. The total is their product.
    orders
        ``(m, d)`` integer index :math:`j_k \\in [-M_k, M_k]` of each member,
        in the C order every contraction here builds.
    frequencies
        ``(m, d)`` :math:`\\omega_{k} = h_k j_k`.
    norms
        ``(m,)`` :math:`\\|\\boldsymbol\\omega\\|`, the isotropic argument a
        spectral density is evaluated at.
    boundary_factor
        The multiple :attr:`half_width` came from, carried for provenance.
    """

    centre: np.ndarray
    half_width: np.ndarray
    spacing: np.ndarray
    counts: tuple[int, ...]
    orders: np.ndarray
    frequencies: np.ndarray
    norms: np.ndarray
    boundary_factor: float

    @property
    def size(self) -> int:
        """How many grid points there are: ``prod(counts)``."""
        return int(self.norms.shape[0])

    @property
    def dimensions(self) -> int:
        """How many axes the grid spans."""
        return len(self.counts)

    @property
    def cell_volume(self) -> float:
        """:math:`\\prod_k h_k`, the rectangle rule's weight."""
        return float(np.prod(self.spacing))


def normalise_grid_counts(declaration: int | Sequence[int]) -> tuple[int, ...]:
    """Read a ``basis_size`` declaration as a per-axis tuple of **odd** counts.

    Odd is not a convenience. The rectangle rule's grid is symmetric about
    zero — that is what makes :math:`K` real and the Toeplitz generator
    Hermitian — and an even count has no centre to be symmetric about.
    """
    counts = normalise_counts(declaration)
    even = [count for count in counts if count % 2 == 0]
    if even:
        raise LikelihoodError(
            f"EquispacedFourierGP's basis_size must be odd on every axis, got {counts!r}. The "
            f"frequency grid runs over -M..M and is symmetric about zero, which is what makes "
            f"the represented covariance real; an even count has no zero to be symmetric about. "
            f"Use {tuple(count + 1 for count in counts)!r}."
        )
    return counts


def fourier_grid(
    points: Any,
    counts: Sequence[int],
    boundary_factor: float = DEFAULT_BOUNDARY_FACTOR,
) -> FourierGrid:
    """The equispaced frequency grid for *points*, in numpy.

    Parameters
    ----------
    points
        ``(n, d)`` coordinates, already reduced to the axes the kernel
        selects. Read in numpy whatever namespace they arrive in: they are
        data.
    counts
        Grid points per axis, odd, one entry per column of *points*.
    boundary_factor
        :math:`c` in :math:`h_k = \\pi/(c S_k)`.

    Notes
    -----
    A degenerate axis — every sample at one coordinate — is given a unit
    half-extent, for :func:`~ampere.core.hsgp.hilbert_basis`'s reason: the
    kernel contributes nothing along an axis it cannot separate, and the
    failure belongs here rather than in the middle of a factorisation.
    """
    block = _as_points(points, "data coordinates")
    dimensions = int(block.shape[1])
    if len(counts) != dimensions:
        raise LikelihoodError(
            f"the equispaced Fourier grid was declared with {len(counts)} axis count(s) "
            f"{tuple(counts)!r} but the coordinates it is built on have {dimensions}."
        )
    if not math.isfinite(boundary_factor) or boundary_factor <= 0.0:
        raise LikelihoodError(
            f"EquispacedFourierGP's boundary_factor must be finite and > 0, got "
            f"{boundary_factor!r}."
        )
    lower = np.min(block, axis=0)
    upper = np.max(block, axis=0)
    centre = 0.5 * (lower + upper)
    extent = 0.5 * (upper - lower)
    extent = np.where(extent > 0.0, extent, 1.0)
    half_width = np.asarray(boundary_factor * extent, dtype=DTYPE)
    spacing = np.asarray(math.pi / half_width, dtype=DTYPE)

    per_axis = [np.arange(-(count // 2), count // 2 + 1, dtype=np.int64) for count in counts]
    grids = np.meshgrid(*per_axis, indexing="ij")
    orders = np.stack([grid.reshape(-1) for grid in grids], axis=-1)
    frequencies = np.asarray(orders, dtype=DTYPE) * spacing[None, :]
    norms = np.sqrt(np.sum(frequencies * frequencies, axis=-1))
    return FourierGrid(
        centre=np.asarray(centre, dtype=DTYPE),
        half_width=half_width,
        spacing=spacing,
        counts=tuple(int(count) for count in counts),
        orders=np.ascontiguousarray(orders),
        frequencies=np.ascontiguousarray(frequencies, dtype=DTYPE),
        norms=np.ascontiguousarray(norms, dtype=DTYPE),
        boundary_factor=float(boundary_factor),
    )


def spectral_weights(kernel: Kernel, grid: FourierGrid, values: Mapping[str, Any]) -> np.ndarray:
    """:math:`w_{\\mathbf j}`, the ``(m,)`` non-negative quadrature weights.

    The only hyperparameter-dependent piece, evaluated through the kernel's own
    :meth:`~ampere.core.kernels.Kernel.spectral_density` so that a fitted
    amplitude and length scale reach it from the one place the closed form
    lives.
    """
    density = np.asarray(
        kernel.spectral_density(grid.norms, values, dimensions=grid.dimensions), dtype=DTYPE
    )
    if not np.all(np.isfinite(density)) or np.any(density < 0.0):
        raise LikelihoodError(
            "the kernel's spectral density is not finite and non-negative at the grid "
            "frequencies, so the quadrature K ~ sum_j w_j exp(i omega_j . r) is not a "
            "covariance. The usual cause is a kernel amplitude or length scale outside its "
            "prior's support; a spectral density is non-negative for every admissible "
            "hyperparameter (Bochner)."
        )
    scale = grid.cell_volume / (2.0 * math.pi) ** grid.dimensions
    return np.asarray(density * scale, dtype=DTYPE)


