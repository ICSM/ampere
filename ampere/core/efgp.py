@dataclasses.dataclass(frozen=True)
class EquispacedFourierGP(GPSolver):
    """Approximate GP algebra on an equispaced Fourier grid (**W5.6 prototype**).

    A ``EXACT = False`` solver in :class:`~ampere.core.HilbertSpaceGP`'s
    comparison class — the conformance suite's ``approximation_order`` /
    ``approximation_floor`` / ``approximation_final`` envelope
    (``tests/conformance/README.md`` §3), because the error falls as the grid
    is refined and floors at the periodisation the spacing fixes, which is the
    same two-parameter statement HSGP makes about its box.

    **This is a measurement prototype, and the reference path only.** W5.6's
    item is a bake-off whose *outcome* is a decision-log row naming which of
    EFGP and Vecchia is promoted to a full three-backend solver; until that
    row is acted on there is no torch or jax twin, so a problem composed with
    this solver is a numpy problem (``DIFFERENTIABLE`` and ``BATCHABLE`` stay
    false, and the capability ladder refuses it on a native backend, which is
    the loud behaviour W2.13 exists to give).

    Parameters
    ----------
    basis_size
        Grid points **per axis**, odd; the total ``m`` is their product. Named
        to match :class:`~ampere.core.HilbertSpaceGP`'s field so the two are
        declared, hashed and read the same way.
    boundary_factor
        The spacing, as :math:`h_k = \\pi/(c S_k)`; see the module docstring
        for why it is the same statement as HSGP's box factor.
    jitter
        A standard deviation added in quadrature to the noise diagonal, the
        same knob, meaning and default as :class:`~ampere.core.DenseGP`'s.

    Examples
    --------
    >>> from ampere.core import Matern32
    >>> solver = EquispacedFourierGP(basis_size=33, boundary_factor=2.0)
    >>> solver.counts
    (33,)
    >>> solver.latent_size(Matern32(0.3, 2.0), 500)
    33
    >>> EquispacedFourierGP(basis_size=(17, 17)).provenance_config()
    {'basis_size': [17, 17], 'boundary_factor': 2.0}
    """

    basis_size: int | tuple[int, ...] = DEFAULT_GRID_SIZE
    boundary_factor: float = DEFAULT_BOUNDARY_FACTOR
    jitter: float = 0.0

    NAME: ClassVar[str] = "EquispacedFourierGP"
    EXACT: ClassVar[bool] = False
    IMPLEMENTED: ClassVar[bool] = True
    #: Woodbury takes extra columns exactly as the dense Cholesky does: one
    #: factorisation of ``M``, ``k`` solves, the log-determinant counted ``k``
    #: times.
    STACKED_RESIDUALS: ClassVar[bool] = True

    def __post_init__(self) -> None:
        object.__setattr__(self, "basis_size", normalise_grid_counts(self.basis_size))
        if not math.isfinite(self.boundary_factor) or self.boundary_factor <= 0.0:
            raise LikelihoodError(
                f"EquispacedFourierGP's boundary_factor must be finite and > 0, got "
                f"{self.boundary_factor!r}. It fixes the grid spacing h = pi / (c S), and the "
                f"quadrature's error is the periodisation of the kernel at period 2 c S, so it "
                f"must be at least 1 for the period to cover the data at all."
            )
        if not math.isfinite(self.jitter) or self.jitter < 0.0:
            raise LikelihoodError(
                f"EquispacedFourierGP's jitter must be finite and >= 0, got {self.jitter!r}."
            )

    @property
    def counts(self) -> tuple[int, ...]:
        """Grid points per axis, normalised to a tuple."""
        return normalise_grid_counts(self.basis_size)

    def provenance_config(self) -> Mapping[str, Any]:
        """The approximation, for the run's attrs — as HSGP's, for its reason."""
        return {
            "basis_size": [int(count) for count in self.counts],
            "boundary_factor": float(self.boundary_factor),
        }

    def latent_size(self, kernel: Kernel, n_samples: int) -> int:
        """``m``, not ``N``: the grid's size, from the declaration alone."""
        del kernel, n_samples
        return basis_size(self.counts)

    def check_compatible(self, kernel: Kernel, observed: FunctionSamples) -> None:
        """The layout and axis rules, plus a spectral density and a matching count."""
        super().check_compatible(kernel, observed)
        selected = kernel.selected_axes([axis.name for axis in observed.axes])
        dimensions = len(selected)
        check_spectral_support(kernel, dimensions, owner=self.NAME)
        counts = self.counts
        if len(counts) != dimensions:
            raise LikelihoodError(
                f"{self.NAME} was declared with basis_size={self.basis_size!r} — "
                f"{len(counts)} axis count(s) — but the kernel selects {dimensions} axis/axes "
                f"{selected!r} of this {type(observed).__name__}. The grid is a tensor product "
                f"with one count per axis, and the total m is their product, so the two must "
                f"agree: pass basis_size={tuple([counts[0]] * dimensions)!r} for the same "
                f"resolution on each."
            )

    # -- internals -----------------------------------------------------------

    def _grid(self, kernel: Kernel, points: np.ndarray) -> FourierGrid:
        return fourier_grid(kernel.select(points), self.counts, self.boundary_factor)

    def _diagonal(self, variance: np.ndarray) -> np.ndarray:
        diagonal = _as_float64(variance, "noise variances") + self.jitter**2
        if not np.all(np.isfinite(diagonal)) or np.any(diagonal <= 0.0):
            raise LikelihoodError(
                f"{self.NAME} needs a strictly positive noise diagonal: the Woodbury identity it "
                f"solves by inverts diag(sigma^2 + jitter^2) directly, so a zero uncertainty is "
                f"a division by zero rather than an ill-conditioned matrix. Pass "
                f"{self.NAME}(jitter=...) — a standard deviation in the data's units — or use "
                f"DenseGP, whose Cholesky needs only K + diag(sigma^2) to be positive definite."
            )
        return diagonal

    def _normal_factor(
        self,
        grid: FourierGrid,
        points: np.ndarray,
        weights: np.ndarray,
        diagonal: np.ndarray,
    ) -> tuple[np.ndarray, tuple[np.ndarray, bool]]:
        """``(sqrt(w), cho_factor(M))`` — the one factorisation everything uses."""
        generator = toeplitz_generator(grid, points, 1.0 / diagonal)
        root = np.sqrt(weights)
        matrix = toeplitz_matrix(grid, generator)
        matrix = matrix * root[:, None] * root[None, :]
        matrix[np.diag_indices_from(matrix)] += 1.0
        try:
            factor = scipy.linalg.cho_factor(matrix, lower=True)
        except scipy.linalg.LinAlgError as error:
            raise LikelihoodError(
                f"the equispaced-Fourier normal matrix I + Phi^H D^-1 Phi is not positive "
                f"definite, so the Woodbury solve failed ({error}). It is positive definite for "
                f"every admissible hyperparameter, so this is a numerical rather than a "
                f"structural failure: reduce basis_size, or raise the jitter."
            ) from error
        return root, factor

    def _right_hand_side(
        self,
        grid: FourierGrid,
        points: np.ndarray,
        root: np.ndarray,
        residuals: np.ndarray,
        diagonal: np.ndarray,
    ) -> np.ndarray:
        """:math:`\\tilde\\Phi^{\\mathsf H} D^{-1} r`, ``(m,)`` or ``(m, k)``."""
        if residuals.ndim == 1:
            return root * _projection(grid, points, residuals / diagonal)
        return np.stack(
            [
                root * _projection(grid, points, residuals[:, column] / diagonal)
                for column in range(residuals.shape[1])
            ],
            axis=-1,
        )

    def _features(self, grid: FourierGrid, root: np.ndarray, points: np.ndarray) -> np.ndarray:
        """:math:`\\tilde\\Phi` at *points*, ``(n, m)`` complex.

        Formed only where a per-sample quantity needs it — the leave-one-out
        terms and the conditional variance — never in the marginal likelihood,
        which is the whole reason the method is cheap. Callers chunk.
        """
        centred = _centred(grid, points)
        rows = int(centred.shape[0])
        block = np.ones((rows, 1), dtype=CDTYPE)
        for axis, count in enumerate(grid.counts):
            wave = _phases(
                grid, centred, axis, np.arange(-(count // 2), count // 2 + 1, dtype=np.int64)
            )
            block = (block[:, :, None] * wave[:, None, :]).reshape(rows, -1)
        return np.asarray(block * root[None, :], dtype=CDTYPE)

    def _chunk(self, size: int, columns: int) -> int:
        """Rows per chunk, so a per-sample pass stays inside ~64 MiB."""
        budget = 64 * 1024 * 1024 // (16 * max(columns, 1))
        return max(1, min(size, int(budget)))

    # -- the interface -------------------------------------------------------

    def log_marginal_likelihood(
        self,
        kernel: Kernel,
        coordinates: np.ndarray,
        residual: np.ndarray,
        variance: np.ndarray,
        values: Mapping[str, Any],
    ) -> float:
        """The marginal likelihood **of the quadrature**, summed over the columns.

        Not of the declared kernel: :attr:`EXACT` is ``False`` and this is what
        that means. It is the exact marginal likelihood of the rank-``m``
        process :math:`\\tilde\\Phi\\tilde\\Phi^{\\mathsf H}`, which converges
        to the declared one as the grid is refined in both its parameters.
        """
        points = _as_points(coordinates, "data coordinates")
        residuals = _as_float64(residual, "residuals")
        grid = self._grid(kernel, points)
        selected = kernel.select(points)
        weights = spectral_weights(kernel, grid, values)
        diagonal = self._diagonal(variance)
        root, factor = self._normal_factor(grid, selected, weights, diagonal)
        projected = self._right_hand_side(grid, selected, root, residuals, diagonal)
        log_determinant = float(np.sum(np.log(diagonal))) + 2.0 * float(
            np.sum(np.log(np.abs(np.diag(factor[0]))))
        )
        direct = float(
            np.sum(residuals * residuals / (diagonal if residuals.ndim == 1 else diagonal[:, None]))
        )
        corrected = float(np.real(np.vdot(projected, scipy.linalg.cho_solve(factor, projected))))
        columns = _components(residuals)
        return -0.5 * (direct - corrected + columns * log_determinant + residuals.size * _LOG_2PI)

    def conditional_loo(
        self,
        kernel: Kernel,
        coordinates: np.ndarray,
        residual: np.ndarray,
        variance: np.ndarray,
        values: Mapping[str, Any],
    ) -> np.ndarray:
        """Sundararajan & Keerthi's identity, exact in the quadrature.

        Woodbury gives :math:`(A^{-1})_{ii}` in closed form without forming
        :math:`A`, exactly as :class:`~ampere.core.HilbertSpaceGP`'s does —
        but it needs the rows of :math:`\\tilde\\Phi`, so this is the one
        quantity that costs :math:`O(N m^2)` and the one place EFGP has no
        advantage over HSGP. It is chunked rather than refused because the
        arithmetic is sound; the cost is recorded in ``likelihoods.md`` §7.
        """
        points = _as_points(coordinates, "data coordinates")
        residuals = _as_float64(residual, "residuals")
        grid = self._grid(kernel, points)
        selected = kernel.select(points)
        weights = spectral_weights(kernel, grid, values)
        diagonal = self._diagonal(variance)
        root, factor = self._normal_factor(grid, selected, weights, diagonal)
        projected = self._right_hand_side(grid, selected, root, residuals, diagonal)
        correction = scipy.linalg.cho_solve(factor, projected)

        rows = int(residuals.shape[0])
        columns = _components(residuals)
        divisor = diagonal if residuals.ndim == 1 else diagonal[:, None]
        alpha = residuals / divisor
        precision = 1.0 / diagonal
        step = self._chunk(rows, grid.size)
        for start in range(0, rows, step):
            stop = min(start + step, rows)
            block = self._features(grid, root, selected[start:stop])
            alpha[start:stop] -= np.real(block @ correction) / divisor[start:stop]
            triangular = scipy.linalg.solve_triangular(
                factor[0], (block / diagonal[start:stop, None]).conj().T, lower=True
            )
            precision[start:stop] -= np.sum(np.abs(triangular) ** 2, axis=0)
        quadratic = np.sum(np.reshape(alpha, (rows, columns)) ** 2, axis=1)
        return np.asarray(
            columns * (0.5 * np.log(precision) - 0.5 * _LOG_2PI) - quadratic / (2.0 * precision),
            dtype=DTYPE,
        )

    def condition(
        self,
        kernel: Kernel,
        coordinates: np.ndarray,
        residual: np.ndarray,
        variance: np.ndarray,
        values: Mapping[str, Any],
        at: np.ndarray | None = None,
    ) -> GPConditional:
        """The posterior of the rank-``m`` process, at ``at`` or at the data.

        The prior variance is the **quadrature's**, for
        :class:`~ampere.core.HilbertSpaceGP`'s reason: mixing an exact prior
        with an approximate correction gives a variance that is the variance of
        nothing and can go negative. Taken consistently the posterior variance
        is :math:`\\|L_M^{-1}\\tilde\\Phi_*^{\\mathsf H}\\|^2`, non-negative at
        every ``m``.
        """
        points = _as_points(coordinates, "data coordinates")
        residuals = _as_float64(residual, "residuals")
        grid = self._grid(kernel, points)
        selected = kernel.select(points)
        weights = spectral_weights(kernel, grid, values)
        diagonal = self._diagonal(variance)
        root, factor = self._normal_factor(grid, selected, weights, diagonal)
        projected = self._right_hand_side(grid, selected, root, residuals, diagonal)
        # tilde-Phi^H alpha, with alpha = (K + D)^-1 r, entirely on the grid.
        coefficients = projected - (
            self._normal_projection(grid, selected, root, diagonal, projected, factor)
        )
        if at is None:
            target = selected
        else:
            target = kernel.select(_as_points(at, "conditioning grid", dimensions=points.shape[1]))
        target = np.ascontiguousarray(target, dtype=DTYPE)
        rows = int(target.shape[0])
        columns = _components(residuals)
        mean = np.zeros((rows, columns), dtype=DTYPE) if residuals.ndim != 1 else np.zeros(rows)
        posterior = np.zeros(rows, dtype=DTYPE)
        step = self._chunk(rows, grid.size)
        for start in range(0, rows, step):
            stop = min(start + step, rows)
            block = self._features(grid, root, target[start:stop])
            mean[start:stop] = np.real(block @ coefficients)
            triangular = scipy.linalg.solve_triangular(factor[0], block.conj().T, lower=True)
            posterior[start:stop] = np.sum(np.abs(triangular) ** 2, axis=0)
        return GPConditional(mean=mean, variance=posterior)

    def _normal_projection(
        self,
        grid: FourierGrid,
        points: np.ndarray,
        root: np.ndarray,
        diagonal: np.ndarray,
        projected: np.ndarray,
        factor: tuple[np.ndarray, bool],
    ) -> np.ndarray:
        """:math:`C M^{-1} \\tilde\\Phi^{\\mathsf H} D^{-1} r`, with ``C = M - I``.

        The identity that keeps :meth:`condition` off the ``(N, m)`` block for
        its *mean*: :math:`\\tilde\\Phi^{\\mathsf H}(K+D)^{-1} r = (I -
        C M^{-1}) \\tilde\\Phi^{\\mathsf H} D^{-1} r` with
        :math:`C = \\tilde\\Phi^{\\mathsf H} D^{-1}\\tilde\\Phi`, and ``C``
        applies by FFT.
        """
        generator = toeplitz_generator(grid, points, 1.0 / diagonal)
        solved = scipy.linalg.cho_solve(factor, projected)
        if solved.ndim == 1:
            return root * toeplitz_matvec(grid, generator, root * solved)
        return np.stack(
            [
                root * toeplitz_matvec(grid, generator, root * solved[:, column])
                for column in range(solved.shape[1])
            ],
            axis=-1,
        )

    def latent_transform(
        self,
        kernel: Kernel,
        coordinates: np.ndarray,
        whitened: np.ndarray,
        values: Mapping[str, Any],
        *,
        jitter: float = 1e-10,
    ) -> np.ndarray:
        """``f = Psi z`` — the real cosine/sine whitening, from ``m`` variables.

        The complex grid and the real feature pair represent the *same*
        covariance (:func:`real_features`), so this is the same approximation
        the marginal likelihood scores; the stabilising ``jitter`` is accepted
        and unused, because :math:`\\Psi\\Psi^{\\mathsf T}` is positive
        semi-definite by construction with no factorisation to stabilise.
        """
        del jitter
        points = _as_points(coordinates, "data coordinates")
        draws = _as_float64(whitened, "whitened latent draws")
        grid = self._grid(kernel, points)
        weights = spectral_weights(kernel, grid, values)
        if np.shape(draws)[0] != grid.size:
            raise LikelihoodError(
                f"{self.NAME} whitens {grid.size} Fourier coefficient(s), but it was handed "
                f"{np.shape(draws)[0]} whitened value(s). This solver's latent block is the "
                f"grid size m, not the sample count — see GPSolver.latent_size."
            )
        return real_features(grid, weights, kernel.select(points)) @ draws
